export const projectPath = (lang: Lang, slug: string) => `${routes.work[lang]}/${slug}`;

/** Nájde cestu v druhom jazyku pre aktuálnu stránku */
export function alternatePath(pathname: string, to: Lang): string {
  const clean = pathname.replace(/\/$/, '') || '/';
  for (const r of Object.values(routes)) {
    for (const l of langs) {
      const base = r[l].replace(/\/$/, '') || '/';
      if (clean === base) return r[to];
      if (base !== '/' && base !== '/en' && clean.startsWith(base + '/')) return r[to] + clean.slice(base.length);
    }
  }
  return routes.home[to];
}

